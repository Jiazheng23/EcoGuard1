-- Repair accounts rejected by the legacy flow, which incorrectly converted
-- applicants into tourists. Rejected applicants remain gated and may resubmit.
update public.profiles as profile
set role = 'pending_location_admin', location_id = null
from public.location_admin_applications as application
where application.user_id = profile.id
  and application.status = 'rejected'
  and profile.role = 'tourist';

update auth.users as auth_user
set raw_app_meta_data = (coalesce(auth_user.raw_app_meta_data, '{}'::jsonb) - 'location_id')
  || jsonb_build_object('role', 'pending_location_admin')
from public.location_admin_applications as application
where application.user_id = auth_user.id
  and application.status = 'rejected';

