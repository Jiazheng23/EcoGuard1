-- Replace existing policies so older broad "admin" policies cannot bypass this model.
do $$
declare item record;
begin
  for item in
    select schemaname, tablename, policyname
    from pg_policies
    where schemaname = 'public'
      and tablename in ('profiles', 'ecological_locations', 'crowd_thresholds', 'location_metrics')
  loop
    execute format('drop policy %I on %I.%I', item.policyname, item.schemaname, item.tablename);
  end loop;
end $$;

