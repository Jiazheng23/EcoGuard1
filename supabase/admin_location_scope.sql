create table if not exists public.location_admin_applications (
  id bigint generated by default as identity primary key,
  user_id uuid not null unique,
  requested_location_id bigint,
  requested_location_name text,
  requested_location_address text,
  requested_latitude double precision,
  requested_longitude double precision,
  requested_state text,
  location_method text not null default 'existing'
    check (location_method in ('existing', 'search', 'address')),
  company_document_path text not null,
  company_document_name text not null,
  status text not null default 'pending'
    check (status in ('pending', 'approved', 'rejected')),
  reviewed_by uuid,
  reviewed_at timestamptz,
  created_at timestamptz not null default now(),
  constraint location_admin_applications_user_id_fkey
    foreign key (user_id) references public.profiles(id) on delete cascade,
  constraint location_admin_applications_requested_location_id_fkey
    foreign key (requested_location_id) references public.ecological_locations(id) on delete restrict,
  constraint location_admin_applications_reviewed_by_fkey
    foreign key (reviewed_by) references public.profiles(id) on delete set null
);

