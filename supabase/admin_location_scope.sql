create or replace function public.current_app_role()
returns text language sql stable
set search_path = ''
return coalesce((select auth.jwt() -> 'app_metadata' ->> 'role'), 'tourist');

create or replace function public.current_location_id()
returns bigint language sql stable
set search_path = ''
return nullif((select auth.jwt() -> 'app_metadata' ->> 'location_id'), '')::bigint;

revoke all on function public.current_app_role() from public;
revoke all on function public.current_location_id() from public;
grant execute on function public.current_app_role() to authenticated;
grant execute on function public.current_location_id() to authenticated;

