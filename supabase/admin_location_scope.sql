create policy profiles_read_own_or_super on public.profiles
for select to authenticated
using ((select auth.uid()) = id or (select public.current_app_role()) = 'super_admin');

create policy profiles_insert_own_tourist on public.profiles
for insert to authenticated
with check ((select auth.uid()) = id and role = 'tourist' and location_id is null);

create policy profiles_update_own_safe on public.profiles
for update to authenticated
using ((select auth.uid()) = id or (select public.current_app_role()) = 'super_admin')
with check (
  (
    (select auth.uid()) = id
    and role = (select public.current_app_role())
    and (
      (role = 'tourist' and location_id is null)
      or (
        role = 'location_admin'
        and location_id = (select public.current_location_id())
      )
    )
  )
  or (select public.current_app_role()) = 'super_admin'
);

create policy locations_read on public.ecological_locations
for select to authenticated
using (
  (select public.current_app_role()) = 'super_admin'
  or (
    (select public.current_app_role()) = 'location_admin'
    and id = (select public.current_location_id())
  )
  or (
    (select public.current_app_role()) in ('tourist', 'pending_location_admin')
    and is_active
  )
);

create policy locations_insert_super on public.ecological_locations
