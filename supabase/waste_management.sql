create or replace function public.can_manage_waste(target_location_id bigint)
returns boolean
language sql
stable
set search_path = ''
return (
  (select public.current_app_role()) = 'super_admin'
  or (
    (select public.current_app_role()) = 'location_admin'
    and target_location_id = (select public.current_location_id())
  )
);

