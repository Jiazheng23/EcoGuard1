-- EcoGuard Waste Management Module
-- Phase 2 database schema, validation, indexes, audit data, and RLS.
--
-- Prerequisite:
--   Apply supabase/admin_location_scope.sql first. It creates the trusted
--   current_app_role() and current_location_id() authorization helpers.
--
-- Simulated current readings remain in public.location_metrics with
-- source = 'simulated'. They are deliberately separate from collection
-- schedules and collection-history records.

begin;

create schema if not exists extensions;
create extension if not exists btree_gist with schema extensions;
set local search_path = public, extensions;

do $$
begin
  if to_regclass('public.profiles') is null
    or to_regclass('public.ecological_locations') is null
    or to_regclass('public.location_metrics') is null then
    raise exception 'EcoGuard base tables are missing. Apply the base schema before waste_management.sql.';
  end if;

  if to_regprocedure('public.current_app_role()') is null
    or to_regprocedure('public.current_location_id()') is null then
    raise exception 'Apply supabase/admin_location_scope.sql before waste_management.sql.';
  end if;
end $$;

create table if not exists public.waste_collection_schedules (
  id bigint generated by default as identity primary key,
  location_id bigint not null,
  scheduled_for timestamptz not null,
  scheduled_until timestamptz not null,
  waste_type text not null,
  assigned_team text not null,
  status text not null default 'scheduled',
  notes text,
  created_by uuid not null default auth.uid(),
  updated_by uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint waste_collection_schedules_location_fkey
    foreign key (location_id)
    references public.ecological_locations(id)
    on delete restrict,
  constraint waste_collection_schedules_created_by_fkey
    foreign key (created_by)
    references public.profiles(id)
    on delete restrict,
  constraint waste_collection_schedules_updated_by_fkey
    foreign key (updated_by)
    references public.profiles(id)
    on delete restrict,
  constraint waste_collection_schedules_type_check
    check (waste_type in ('mixed', 'recyclable', 'organic', 'hazardous')),
  constraint waste_collection_schedules_status_check
    check (status in ('scheduled', 'completed', 'cancelled', 'missed')),
  constraint waste_collection_schedules_time_check
    check (scheduled_until > scheduled_for),
  constraint waste_collection_schedules_team_check
    check (length(btrim(assigned_team)) > 0),
  constraint waste_collection_schedules_id_location_unique
    unique (id, location_id),
  constraint waste_collection_schedules_no_overlap
    exclude using gist (
      location_id with =,
      tstzrange(scheduled_for, scheduled_until, '[)') with &&
    )
    where (status = 'scheduled')
);

comment on table public.waste_collection_schedules is
  'Planned waste-collection periods. Active schedules at one location cannot overlap.';
comment on column public.waste_collection_schedules.scheduled_for is
  'Inclusive collection-window start stored as timestamptz.';
comment on column public.waste_collection_schedules.scheduled_until is
  'Exclusive collection-window end stored as timestamptz.';

create table if not exists public.waste_collection_records (
  id bigint generated by default as identity primary key,
  schedule_id bigint,
  location_id bigint not null,
  collected_at timestamptz not null default now(),
  total_kg numeric(12, 2) not null default 0,
  recycled_kg numeric(12, 2) not null default 0,
  landfill_kg numeric(12, 2)
    generated always as (total_kg - recycled_kg) stored,
  waste_type text not null,
  status text not null,
  source text not null default 'manual',
  notes text,
  recorded_by uuid not null default auth.uid(),
  created_at timestamptz not null default now(),

  constraint waste_collection_records_schedule_unique
    unique (schedule_id),
  constraint waste_collection_records_schedule_location_fkey
    foreign key (schedule_id, location_id)
    references public.waste_collection_schedules(id, location_id)
    on delete restrict,
  constraint waste_collection_records_location_fkey
    foreign key (location_id)
    references public.ecological_locations(id)
    on delete restrict,
  constraint waste_collection_records_recorded_by_fkey
    foreign key (recorded_by)
    references public.profiles(id)
    on delete restrict,
  constraint waste_collection_records_type_check
    check (waste_type in ('mixed', 'recyclable', 'organic', 'hazardous')),
  constraint waste_collection_records_status_check
    check (status in ('completed', 'partial', 'missed')),
  constraint waste_collection_records_source_check
    check (source in ('manual', 'simulated_sensor')),
  constraint waste_collection_records_total_check
    check (total_kg >= 0),
  constraint waste_collection_records_recycled_check
    check (recycled_kg >= 0 and recycled_kg <= total_kg),
  constraint waste_collection_records_status_quantity_check
    check (
      (status = 'missed' and total_kg = 0 and recycled_kg = 0)
      or (status in ('completed', 'partial') and total_kg > 0)
    )
);

comment on table public.waste_collection_records is
  'Persisted results of scheduled or unscheduled waste-collection attempts.';
comment on column public.waste_collection_records.source is
  'manual or simulated_sensor; simulated records must be labelled in the UI and reports.';
comment on column public.waste_collection_records.landfill_kg is
  'Derived quantity equal to total_kg minus recycled_kg.';

create table if not exists public.waste_thresholds (
  location_id bigint primary key,
  moderate_kg numeric(12, 2) not null,
  high_risk_kg numeric(12, 2) not null,
  critical_kg numeric(12, 2) not null,
  updated_by uuid not null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),

  constraint waste_thresholds_location_fkey
    foreign key (location_id)
    references public.ecological_locations(id)
    on delete cascade,
  constraint waste_thresholds_updated_by_fkey
    foreign key (updated_by)
    references public.profiles(id)
    on delete restrict,
  constraint waste_thresholds_order_check
    check (
      moderate_kg > 0
      and moderate_kg < high_risk_kg
      and high_risk_kg < critical_kg
    )
);

