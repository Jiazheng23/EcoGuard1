create or replace function public.complete_waste_collection(
  p_schedule_id bigint,
  p_collected_at timestamptz,
  p_total_kg numeric,
  p_recycled_kg numeric,
  p_status text,
  p_source text,
  p_notes text default null
)
returns public.waste_collection_records
language plpgsql
security invoker
set search_path = ''
as $$
declare
  schedule_row public.waste_collection_schedules%rowtype;
  collection_row public.waste_collection_records%rowtype;
  final_schedule_status text;
begin
  select *
  into schedule_row
  from public.waste_collection_schedules
  where id = p_schedule_id
  for update;

  if not found then
    raise exception using
      errcode = 'P0002',
      message = 'Waste collection schedule was not found.';
  end if;

  if not public.can_manage_waste(schedule_row.location_id) then
    raise exception using
      errcode = '42501',
      message = 'You are not authorized to complete this waste collection schedule.';
  end if;

  if schedule_row.status <> 'scheduled' then
    raise exception using
      errcode = '23514',
      message = 'Only an active scheduled collection can be completed or marked missed.';
  end if;

  final_schedule_status := case
    when p_status = 'missed' then 'missed'
    else 'completed'
  end;

  insert into public.waste_collection_records (
    schedule_id,
    location_id,
    collected_at,
    total_kg,
    recycled_kg,
    waste_type,
    status,
    source,
    notes,
    recorded_by
  ) values (
    schedule_row.id,
    schedule_row.location_id,
    p_collected_at,
    p_total_kg,
    p_recycled_kg,
    schedule_row.waste_type,
    p_status,
    p_source,
    nullif(btrim(p_notes), ''),
    auth.uid()
  )
  returning * into collection_row;

  update public.waste_collection_schedules
  set
    status = final_schedule_status,
    updated_by = auth.uid()
  where id = schedule_row.id;

  return collection_row;
end;
$$;

