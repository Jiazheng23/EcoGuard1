create or replace function public.get_tourist_environmental_indicators()
returns table (
  location_id bigint,
  crowd_level text,
  warning_level text,
  environment_condition text,
  waste_level text,
  recycling_rate numeric,
  recorded_at timestamptz,
  data_source text
)
language sql
stable
security definer
set search_path = ''
as $$
  with latest_metric as (
    select distinct on (metric.location_id)
      metric.location_id,
      metric.crowd_count,
      metric.waste_kg,
      metric.recycled_kg,
      metric.air_quality_index,
      metric.water_quality_score,
      metric.recorded_at,
      metric.source
    from public.location_metrics metric
    order by metric.location_id, metric.recorded_at desc
  ), scored as (
    select
      location.id as location_id,
      metric.crowd_count,
      metric.waste_kg,
      metric.recycled_kg,
      metric.air_quality_index,
      metric.water_quality_score,
      metric.recorded_at,
      metric.source,
      100.0 * coalesce(metric.crowd_count, 0) / greatest(location.max_capacity, 1) as occupancy_percent,
      coalesce(crowd.caution_percent, 60) as caution_percent,
      coalesce(crowd.warning_percent, 80) as warning_percent,
      coalesce(crowd.critical_percent, 90) as critical_percent,
      waste.moderate_kg,
      waste.high_risk_kg,
      waste.critical_kg
    from public.ecological_locations location
    left join latest_metric metric on metric.location_id = location.id
    left join public.crowd_thresholds crowd on crowd.location_id = location.id
    left join public.waste_thresholds waste on waste.location_id = location.id
    where location.is_active
  )
  select
    scored.location_id,
    case
      when scored.recorded_at is null then 'Awaiting data'
      when scored.occupancy_percent >= scored.critical_percent then 'Critical'
      when scored.occupancy_percent >= scored.warning_percent then 'High'
      when scored.occupancy_percent >= scored.caution_percent then 'Moderate'
      else 'Low'
    end as crowd_level,
    case
      when scored.recorded_at is null then 'Awaiting data'
      when scored.occupancy_percent >= scored.critical_percent then 'Critical'
      when scored.occupancy_percent >= scored.warning_percent then 'High Risk'
      when scored.occupancy_percent >= scored.caution_percent then 'Caution'
      else 'Safe'
    end as warning_level,
    case
      when scored.recorded_at is null then 'Awaiting data'
      when scored.air_quality_index <= 50 and scored.water_quality_score >= 80 then 'Excellent'
      when scored.air_quality_index <= 100 and scored.water_quality_score >= 65 then 'Good'
      when scored.air_quality_index <= 150 and scored.water_quality_score >= 50 then 'Fair'
      else 'Poor'
    end as environment_condition,
    case
      when scored.recorded_at is null then 'Awaiting data'
      when scored.moderate_kg is null then 'Not configured'
      when scored.waste_kg >= scored.critical_kg then 'Critical'
      when scored.waste_kg >= scored.high_risk_kg then 'High Risk'
      when scored.waste_kg >= scored.moderate_kg then 'Moderate'
      else 'Normal'
    end as waste_level,
    case
      when scored.recorded_at is null or scored.waste_kg <= 0 then null
      else round((100.0 * scored.recycled_kg / scored.waste_kg)::numeric, 1)
    end as recycling_rate,
    scored.recorded_at,
    case
      when scored.recorded_at is null then 'unavailable'
      when scored.source = 'simulated' then 'simulated'
      else 'stored_estimate'
    end as data_source
  from scored
  order by scored.location_id;
$$;

