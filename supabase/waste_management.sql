create or replace function public.set_waste_row_updated_at()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  new.updated_at := now();

  if tg_table_name = 'waste_collection_schedules' then
    new.updated_by := coalesce(auth.uid(), new.updated_by, old.updated_by);
  elsif tg_table_name = 'waste_thresholds' then
    new.updated_by := coalesce(auth.uid(), new.updated_by, old.updated_by);
  end if;

  return new;
end;
$$;

create or replace function public.validate_future_waste_schedule()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.status = 'scheduled'
    and new.scheduled_for <= now()
    and (
      tg_op = 'INSERT'
      or new.scheduled_for is distinct from old.scheduled_for
      or new.status is distinct from old.status
    ) then
    raise exception using
      errcode = '22007',
      message = 'An active waste collection schedule must start in the future.';
  end if;

  return new;
end;
$$;

create or replace function public.validate_waste_collection_time()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if new.collected_at > now() then
    raise exception using
      errcode = '22007',
      message = 'Waste collection time cannot be in the future.';
  end if;

  return new;
end;
$$;

